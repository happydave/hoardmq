// Command coverage renders conformance/COVERAGE.md from the statements files,
// the scope file and the latest results file. Run it from the module root
// after `go test ./conformance -conformance.results=conformance/results.json`.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type statement struct {
	ID   string `json:"id"`
	Text string `json:"text"`
}

type result struct {
	Tests []string `json:"tests"`
	Pass  bool     `json:"pass"`
}

type scopeEntry struct {
	Status string `json:"status"`
	Reason string `json:"reason"`
}

// external mirrors conformance/external/paho/expected.json and last-run.json.
type external struct {
	Upstream string `json:"upstream"`
	Commit   string `json:"commit"`
	Suites   map[string]struct {
		Ran              int               `json:"ran"`
		ExpectedFailures map[string]string `json:"expectedFailures"`
	} `json:"suites"`
	NotRun map[string]string `json:"notRun"`
}

type lastRun struct {
	Commit string `json:"commit"`
	Suites map[string]struct {
		Ran      int      `json:"ran"`
		Passed   int      `json:"passed"`
		Failures []string `json:"failures"`
	} `json:"suites"`
}

func main() {
	dir := flag.String("dir", "conformance", "conformance directory")
	out := flag.String("out", "", "output file (default <dir>/COVERAGE.md)")
	flag.Parse()
	if *out == "" {
		*out = filepath.Join(*dir, "COVERAGE.md")
	}
	if err := run(*dir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "coverage:", err)
		os.Exit(1)
	}
}

func run(dir, out string) error {
	scope := map[string]scopeEntry{}
	if data, err := os.ReadFile(filepath.Join(dir, "statements", "scope.json")); err == nil {
		if err := json.Unmarshal(data, &scope); err != nil {
			return fmt.Errorf("scope.json: %w", err)
		}
	}
	results := map[string]*result{}
	resultsPath := filepath.Join(dir, "results.json")
	if data, err := os.ReadFile(resultsPath); err == nil {
		if err := json.Unmarshal(data, &results); err != nil {
			return fmt.Errorf("results.json: %w", err)
		}
	} else {
		fmt.Fprintln(os.Stderr, "coverage: no results.json; every statement renders as not-covered")
	}
	var b strings.Builder
	b.WriteString("# Conformance coverage\n\n")
	b.WriteString("Generated by `go run ./conformance/cmd/coverage` from `conformance/statements/*.json`, `conformance/statements/scope.json` and `conformance/results.json` (written by `go test ./conformance -conformance.results=conformance/results.json`). Do not edit by hand.\n\n")
	b.WriteString("Status meanings: `pass` every covering test passed; `fail` a covering test failed; `not-covered` no test observes the statement yet; `n/a-client` the statement binds only a client and has no observable server behaviour (reason in scope.json).\n\n")
	specs := []struct{ title, file string }{{"MQTT 5.0 (Appendix B)", "mqtt5.json"}, {"MQTT 3.1.1 (Appendix B, Plus Errata 01)", "mqtt311.json"}}
	for _, spec := range specs {
		data, err := os.ReadFile(filepath.Join(dir, "statements", spec.file))
		if err != nil {
			return err
		}
		var list []statement
		if err := json.Unmarshal(data, &list); err != nil {
			return fmt.Errorf("%s: %w", spec.file, err)
		}
		counts := map[string]int{}
		type row struct{ id, status, tests, text string }
		rows := make([]row, 0, len(list))
		for _, s := range list {
			status := "not-covered"
			tests := ""
			if sc, ok := scope[s.ID]; ok && sc.Status == "n/a-client" {
				status = "n/a-client"
				tests = sc.Reason
			}
			if r, ok := results[s.ID]; ok {
				if r.Pass {
					status = "pass"
				} else {
					status = "fail"
				}
				names := append([]string(nil), r.Tests...)
				sort.Strings(names)
				tests = strings.Join(names, ", ")
			}
			counts[status]++
			rows = append(rows, row{s.ID, status, tests, s.Text})
		}
		fmt.Fprintf(&b, "## %s\n\n", spec.title)
		fmt.Fprintf(&b, "%d statements: %d pass, %d fail, %d not-covered, %d n/a-client.\n\n", len(list), counts["pass"], counts["fail"], counts["not-covered"], counts["n/a-client"])
		b.WriteString("| Statement | Status | Tests or reason | Text |\n|---|---|---|---|\n")
		for _, r := range rows {
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", r.id, r.status, escape(r.tests), escape(r.text))
		}
		b.WriteString("\n")
	}
	if err := externalSection(&b, dir); err != nil {
		return err
	}
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// externalSection renders the third-party suite outcomes recorded by
// conformance/external (HOARDMQ_EXTERNAL=1 go test ./conformance/external).
func externalSection(b *strings.Builder, dir string) error {
	var exp external
	data, err := os.ReadFile(filepath.Join(dir, "external", "paho", "expected.json"))
	if err != nil {
		return nil
	}
	if err := json.Unmarshal(data, &exp); err != nil {
		return fmt.Errorf("expected.json: %w", err)
	}
	b.WriteString("## External suites\n\n")
	fmt.Fprintf(b, "Eclipse Paho interoperability suites from %s at commit `%s`, run by `HOARDMQ_EXTERNAL=1 go test ./conformance/external` against an in-process node. Expected failures are recorded in `conformance/external/paho/expected.json` with their reasons; the last recorded run is `last-run.json`.\n\n", exp.Upstream, exp.Commit)
	var last lastRun
	if data, err := os.ReadFile(filepath.Join(dir, "external", "paho", "last-run.json")); err == nil {
		if err := json.Unmarshal(data, &last); err != nil {
			return fmt.Errorf("last-run.json: %w", err)
		}
	}
	names := make([]string, 0, len(exp.Suites))
	for name := range exp.Suites {
		names = append(names, name)
	}
	sort.Strings(names)
	b.WriteString("| Suite | Ran | Passed | Failures (expected, with reason) |\n|---|---|---|---|\n")
	for _, name := range names {
		run, ok := last.Suites[name]
		if !ok {
			fmt.Fprintf(b, "| %s | not run | | |\n", name)
			continue
		}
		var fails []string
		for _, f := range run.Failures {
			reason := exp.Suites[name].ExpectedFailures[f]
			if reason == "" {
				reason = "UNEXPECTED"
			}
			fails = append(fails, f+": "+reason)
		}
		fmt.Fprintf(b, "| %s | %d | %d | %s |\n", name, run.Ran, run.Passed, escape(strings.Join(fails, "; ")))
	}
	b.WriteString("\n")
	notRun := make([]string, 0, len(exp.NotRun))
	for name := range exp.NotRun {
		notRun = append(notRun, name)
	}
	sort.Strings(notRun)
	for _, name := range notRun {
		fmt.Fprintf(b, "Not run: %s. %s.\n\n", name, escape(exp.NotRun[name]))
	}
	return nil
}

func escape(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.ReplaceAll(s, "\n", " ")
}
