func TestParseWith(t *testing.T) {
	for _, c := range []struct {
		in                 string
		path, version, dir string
		wantErr            bool
	}{
		{in: "example.com/m", path: "example.com/m"},
		{in: "example.com/m@v1.2.3", path: "example.com/m", version: "v1.2.3"},
		{in: "example.com/m=../d", path: "example.com/m", dir: "../d"},
		{in: "example.com/m@v1.2.3=../d", path: "example.com/m", version: "v1.2.3", dir: "../d"},
		{in: "", wantErr: true},
		{in: "@v1.2.3", wantErr: true},
		{in: "example.com/m@", wantErr: true},
		{in: "example.com/m=", wantErr: true},
		{in: "example.com/a b", wantErr: true},
		{in: "example.com/a\"\n", wantErr: true},
	} {
		m, err := parseWith(c.in)
		if c.wantErr {
			if err == nil {
				t.Errorf("%q: accepted as %+v", c.in, m)
			}
			continue
		}
		if err != nil || m.importPath != c.path || m.version != c.version || m.dir != c.dir {
			t.Errorf("%q: %+v, %v; want path %q version %q dir %q", c.in, m, err, c.path, c.version, c.dir)
		}
	}
}

func writeFile(t *testing.T, path, data string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestResolve: a local directory names its module in its go.mod, and the
// import path must lie in that module.
func TestResolve(t *testing.T) {
	dir := t.TempDir()
	m := module{importPath: "example.com/m", path: "example.com/m", dir: dir}
	if err := m.resolve(); err == nil || !strings.Contains(err.Error(), "go.mod") {
		t.Fatalf("a directory without go.mod: %v", err)
	}
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/m\n\ngo 1.26.4\n")
	sub := module{importPath: "example.com/m/plugin", path: "example.com/m/plugin", dir: dir}
	if err := sub.resolve(); err != nil || sub.path != "example.com/m" {
		t.Fatalf("a package in the module: %+v, %v", sub, err)
	}
	other := module{importPath: "example.com/other", path: "example.com/other", dir: dir}
	if err := other.resolve(); err == nil {
		t.Fatal("an import path outside the directory's module was accepted")
	}
}

// TestGeneratedModule: the build module requires the broker through its
// checkout, a local module through a replace and a versioned one at its
// version, and main imports both, sorted.
func TestGeneratedModule(t *testing.T) {
	b := broker{dir: "/src/hoardmq", goLine: "go 1.26.4"}
	mods := []module{
		{importPath: "example.com/zeta", path: "example.com/zeta", dir: "/src/zeta"},
		{importPath: "example.com/alpha/plug", path: "example.com/alpha", version: "v0.3.0"},
		{importPath: "example.com/latest", path: "example.com/latest"},
	}
	wantMod := `module hoardmq-custom

go 1.26.4

require (
	github.com/happydave/hoardmq v0.0.0-00010101000000-000000000000
	example.com/zeta v0.0.0-00010101000000-000000000000
	example.com/alpha v0.3.0
)

replace (
	github.com/happydave/hoardmq => /src/hoardmq
	example.com/zeta => /src/zeta
)
`
	if got := string(goModSource(b, mods)); got != wantMod {
		t.Errorf("go.mod:\n%s\nwant:\n%s", got, wantMod)
	}
	wantMain := `// Code generated by hoardmq-build. DO NOT EDIT.

// Command hoardmq is the HoardMQ broker binary: it serves, validates
// configuration, and reports its version.
package main

import (
	hoardmqcmd "github.com/happydave/hoardmq/cmd"

	_ "example.com/alpha/plug"
	_ "example.com/latest"
	_ "example.com/zeta"
)

func main() { hoardmqcmd.Main() }
`
	if got := string(mainSource(mods)); got != wantMain {
		t.Errorf("main.go:\n%s\nwant:\n%s", got, wantMain)
	}
	versioned := goModSource(broker{version: "v0.9.0", goLine: defaultGoLine}, nil)
	if !bytes.Contains(versioned, []byte("\tgithub.com/happydave/hoardmq v0.9.0\n")) || bytes.Contains(versioned, []byte("replace")) {
		t.Errorf("a versioned broker:\n%s", versioned)
	}
}

// TestDefaultMainIsGenerated: the default binary's main package is exactly
// the tool's output with no modules, so the default binary and a custom one
// differ only by the modules named.
func TestDefaultMainIsGenerated(t *testing.T) {
	got, err := os.ReadFile(filepath.Join("..", "hoardmq", "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	if want := mainSource(nil); !bytes.Equal(got, want) {
		t.Fatalf("cmd/hoardmq/main.go is not the generated main (go generate ./cmd/hoardmq):\n%s\nwant:\n%s", got, want)
	}
}

// TestDefaultGoLine: a versioned build's go directive is the broker's.
func TestDefaultGoLine(t *testing.T) {
	path, goLine, err := readGoMod(filepath.Join("..", "..", "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	if path != brokerModule || goLine != defaultGoLine {
		t.Fatalf("broker go.mod: module %q, %q; the tool says %q", path, goLine, defaultGoLine)
	}
}

// TestUsage: malformed requests exit 2 without building.
func TestUsage(t *testing.T) {
	other := t.TempDir()
	writeFile(t, filepath.Join(other, "go.mod"), "module example.com/notthebroker\n")
	for _, args := range [][]string{
		{"--with", "example.com/m="},
		{"--with", "example.com/m@"},
		{"stray"},
		{"--hoardmq-version", "v1.0.0", "--hoardmq-dir", "."},
		{"--hoardmq-dir", other},
		{"--hoardmq-dir", filepath.Join("..", ".."), "--with", "example.com/m=" + t.TempDir()},
	} {
		var out, errOut bytes.Buffer
		if code := run(args, &out, &errOut); code != exitUsage {
			t.Errorf("%q: exit %d, want %d (%s)", args, code, exitUsage, errOut.String())
		}
	}
}

// TestMainFlag: --main prints the generated main and builds nothing.
func TestMainFlag(t *testing.T) {
	var out, errOut bytes.Buffer
	if code := run([]string{"--main", "--with", "example.com/m"}, &out, &errOut); code != exitOK {
		t.Fatalf("exit %d: %s", code, errOut.String())
	}
	if !bytes.Equal(out.Bytes(), mainSource([]module{{importPath: "example.com/m"}})) {
		t.Fatalf("printed:\n%s", out.String())
	}
}
