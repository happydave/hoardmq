package main

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// brokerModule is the broker's module path, and cmdPackage the package whose
// Main runs the broker.
const (
	brokerModule = "github.com/happydave/hoardmq"
	cmdPackage   = brokerModule + "/cmd"
)

// defaultGoLine is the go directive of a build whose broker is a version
// rather than a checkout; it matches the broker's own go.mod.
const defaultGoLine = "go 1.26.4"

// placeholder is the version a requirement satisfied by a replace carries.
const placeholder = "v0.0.0-00010101000000-000000000000"

// module is one --with value: an import path, and a version or a local
// directory. path is the module path, read from the directory's go.mod when
// there is one.
type module struct {
	importPath string
	version    string
	dir        string
	path       string
}

// broker is the broker the build requires: a version, or a local checkout
// through a replace.
type broker struct {
	version string
	dir     string
	goLine  string
}

// parseWith reads module[@version][=dir].
func parseWith(s string) (module, error) {
	var m module
	spec, dir, hasDir := strings.Cut(s, "=")
	if hasDir {
		if dir == "" {
			return m, errors.New("an empty directory after =")
		}
		m.dir = dir
	}
	path, version, hasVersion := strings.Cut(spec, "@")
	if path == "" {
		return m, errors.New("no module")
	}
	if hasVersion && version == "" {
		return m, errors.New("an empty version after @")
	}
	if strings.ContainsAny(path, " \t\r\n\"`\\") {
		return m, fmt.Errorf("%q is not an import path", path)
	}
	m.importPath, m.version, m.path = path, version, path
	return m, nil
}

// resolve reads the module path from a local directory's go.mod and makes
// the directory absolute.
func (m *module) resolve() error {
	if m.dir == "" {
		return nil
	}
	abs, err := filepath.Abs(m.dir)
	if err != nil {
		return err
	}
	path, _, err := readGoMod(filepath.Join(abs, "go.mod"))
	if err != nil {
		return err
	}
	if m.importPath != path && !strings.HasPrefix(m.importPath, path+"/") {
		return fmt.Errorf("%s is module %s, which does not hold %s", m.dir, path, m.importPath)
	}
	m.dir, m.path = abs, path
	return nil
}

// readGoMod returns a go.mod's module path and its go directive.
func readGoMod(file string) (path, goLine string, err error) {
	data, err := os.ReadFile(file)
	if err != nil {
		return "", "", err
	}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		switch {
		case strings.HasPrefix(line, "module "):
			path = strings.Trim(strings.TrimSpace(strings.TrimPrefix(line, "module ")), `"`)
		case strings.HasPrefix(line, "go ") && goLine == "":
			goLine = line
		}
	}
	if path == "" {
		return "", "", fmt.Errorf("%s names no module", file)
	}
	if goLine == "" {
		goLine = defaultGoLine
	}
	return path, goLine, nil
}

// mainSource is the main package of a build with mods: the broker's command,
// and a blank import of each module so its init registers it.
func mainSource(mods []module) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by hoardmq-build. DO NOT EDIT.\n\n")
	b.WriteString("// Command hoardmq is the HoardMQ broker binary: it serves, validates\n")
	b.WriteString("// configuration, and reports its version.\n")
	b.WriteString("package main\n\n")
	imports := make([]string, 0, len(mods))
	for _, m := range mods {
		imports = append(imports, m.importPath)
	}
	sort.Strings(imports)
	if len(imports) == 0 {
		b.WriteString("import hoardmqcmd \"" + cmdPackage + "\"\n\n")
	} else {
		b.WriteString("import (\n\thoardmqcmd \"" + cmdPackage + "\"\n\n")
		for i, p := range imports {
			if i > 0 && p == imports[i-1] {
				continue
			}
			b.WriteString("\t_ \"" + p + "\"\n")
		}
		b.WriteString(")\n\n")
	}
	b.WriteString("func main() { hoardmqcmd.Main() }\n")
	return []byte(b.String())
}

// goModSource is the build module's go.mod.
func goModSource(b broker, mods []module) []byte {
	var s strings.Builder
	s.WriteString("module hoardmq-custom\n\n" + b.goLine + "\n\nrequire (\n")
	version := b.version
	if b.dir != "" {
		version = placeholder
	}
	s.WriteString("\t" + brokerModule + " " + version + "\n")
	seen := map[string]bool{brokerModule: true}
	for _, m := range mods {
		if seen[m.path] {
			continue
		}
		seen[m.path] = true
		v := m.version
		if m.dir != "" {
			v = placeholder
		}
		if v == "" {
			continue // go build -mod=mod requires the latest version
		}
		s.WriteString("\t" + m.path + " " + v + "\n")
	}
	s.WriteString(")\n")
	replaces := []string{}
	if b.dir != "" {
		replaces = append(replaces, "\t"+brokerModule+" => "+b.dir+"\n")
	}
	for _, m := range mods {
		if m.dir != "" {
			replaces = append(replaces, "\t"+m.path+" => "+m.dir+"\n")
		}
	}
	if len(replaces) > 0 {
		s.WriteString("\nreplace (\n" + strings.Join(replaces, "") + ")\n")
	}
	return []byte(s.String())
}

// writeModule writes the build module into dir: go.mod, a go.sum seeded from
// every local module's, and main.go.
func writeModule(dir string, b broker, mods []module) error {
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), goModSource(b, mods), 0o644); err != nil {
		return err
	}
	var sum []byte
	sources := []string{}
	if b.dir != "" {
		sources = append(sources, b.dir)
	}
	for _, m := range mods {
		if m.dir != "" {
			sources = append(sources, m.dir)
		}
	}
	for _, d := range sources {
		data, err := os.ReadFile(filepath.Join(d, "go.sum"))
		switch {
		case errors.Is(err, os.ErrNotExist):
			continue
		case err != nil:
			return err
		}
		sum = append(sum, data...)
	}
	if err := os.WriteFile(filepath.Join(dir, "go.sum"), sum, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "main.go"), mainSource(mods), 0o644)
}
